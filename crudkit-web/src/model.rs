macro_rules! impl_dyn_model {
    ($dyn_ty:tt, $erased_ty:tt) => {
        /// Any type-erased (boxed) model.
        #[derive(Debug, Clone, Eq)]
        pub struct $dyn_ty {
            pub(crate) inner: Box<dyn $erased_ty>,
        }

        impl PartialEq for $dyn_ty {
            fn eq(&self, other: &Self) -> bool {
                self.inner.dyn_eq(DynEq::as_any(&other.inner))
            }
        }

        impl<T: $erased_ty> From<T> for $dyn_ty {
            fn from(value: T) -> Self {
                Self {
                    inner: Box::new(value),
                }
            }
        }

        impl $dyn_ty {
            pub fn new<Concrete: $erased_ty>(concrete: Concrete) -> Self {
                Self {
                    inner: Box::new(concrete),
                }
            }

            pub fn downcast<Concrete: $erased_ty>(self) -> Concrete {
                *self.inner.downcast::<Concrete>().expect("correct")
            }

            pub fn downcast_ref<Concrete: $erased_ty>(&self) -> &Concrete {
                self.inner.downcast_ref::<Concrete>().expect("correct")
            }

            pub fn downcast_mut<Concrete: $erased_ty>(&mut self) -> &mut Concrete {
                self.inner.downcast_mut::<Concrete>().expect("correct")
            }

            /// Serializes the model as plain JSON, without the type tag of its erased
            /// serialization.
            ///
            /// # Errors
            ///
            /// Returns an error if the model cannot be serialized, or if its erased serialization
            /// is not an object with exactly one type-tag entry.
            pub fn to_untagged_json(&self) -> Result<serde_json::Value, UntaggedJsonError> {
                untagged_json(&self.inner)
            }
        }

        impl std::ops::Deref for $dyn_ty {
            type Target = dyn $erased_ty;

            fn deref(&self) -> &Self::Target {
                self.inner.as_ref()
            }
        }
    };
}

/// Failure to serialize an erased model without its type tag.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum UntaggedJsonError {
    /// The model could not be serialized.
    #[error("failed to serialize the model: {0}")]
    Serialize(String),
    /// The erased serialization did not wrap the model in exactly one type-tag entry.
    #[error("expected the model to be wrapped in exactly one type-tag entry, found {0}")]
    UnexpectedShape(&'static str),
}

/// Serializes `model` and unwraps the externally tagged object produced by typetag.
fn untagged_json(
    model: &impl erased_serde::Serialize,
) -> Result<serde_json::Value, UntaggedJsonError> {
    let value = erased_serde::serialize(model, serde_json::value::Serializer)
        .map_err(|e| UntaggedJsonError::Serialize(e.to_string()))?;
    match value {
        serde_json::Value::Object(object) if object.len() == 1 => object
            .into_values()
            .next()
            .ok_or(UntaggedJsonError::UnexpectedShape("an empty object")),
        serde_json::Value::Object(_) => Err(UntaggedJsonError::UnexpectedShape(
            "an object with several entries",
        )),
        serde_json::Value::Null => Err(UntaggedJsonError::UnexpectedShape("null")),
        serde_json::Value::Bool(_) => Err(UntaggedJsonError::UnexpectedShape("a boolean")),
        serde_json::Value::Number(_) => Err(UntaggedJsonError::UnexpectedShape("a number")),
        serde_json::Value::String(_) => Err(UntaggedJsonError::UnexpectedShape("a string")),
        serde_json::Value::Array(_) => Err(UntaggedJsonError::UnexpectedShape("an array")),
    }
}

