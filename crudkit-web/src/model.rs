/// Marker trait for type-erased field wrappers (`DynCreateField`, `DynReadField`, `DynUpdateField`).
///
/// This trait is implemented for the `Dyn*Field` wrapper types to provide a common
/// abstraction over all type-erased fields regardless of their model type.
pub trait TypeErasedField:
    Named + Debug + Clone + PartialEq + Eq + Hash + Send + Sync + 'static
{
    /// The type-erased model this field belongs to.
    type Model: Debug + Clone + PartialEq + Send + Sync + 'static;

    /// Writes `value` into this field of `model`.
    fn set_value(&self, model: &mut Self::Model, value: Value);

    /// Returns the kind of value this field holds.
    fn value_kind(&self) -> crudkit_core::ValueKind;

    /// Returns whether this field is optional.
    fn is_optional(&self) -> bool;
}

macro_rules! impl_dyn_field {
    ($dyn_ty:tt, $erased_ty:tt, $dyn_model_ty:tt) => {
        /// Any field. Usable in collections.
        #[derive(Debug, Clone, Eq, serde::Serialize, serde::Deserialize)]
        pub struct $dyn_ty {
            inner: Arc<dyn $erased_ty>,
        }

        impl PartialEq for $dyn_ty {
            fn eq(&self, other: &Self) -> bool {
                self.inner.dyn_eq(DynEq::as_any(&other.inner))
            }
        }

        impl std::hash::Hash for $dyn_ty {
            fn hash<H: std::hash::Hasher>(&self, state: &mut H) {
                self.inner.dyn_hash(state);
            }
        }

        impl<T: $erased_ty> From<T> for $dyn_ty {
            fn from(value: T) -> Self {
                Self {
                    inner: Arc::new(value),
                }
            }
        }

        impl $dyn_ty {
            pub fn new<Concrete: $erased_ty>(concrete: Concrete) -> Self {
                Self {
                    inner: Arc::new(concrete),
                }
            }
        }

        impl std::ops::Deref for $dyn_ty {
            type Target = dyn $erased_ty;

            fn deref(&self) -> &Self::Target {
                self.inner.as_ref()
            }
        }

        impl Named for $dyn_ty {
            fn name(&self) -> std::borrow::Cow<'static, str> {
                self.inner.name()
            }
        }

        impl TypeErasedField for $dyn_ty {
            type Model = $dyn_model_ty;

            fn set_value(&self, model: &mut $dyn_model_ty, value: Value) {
                $erased_ty::set_value(self.inner.as_ref(), model, value);
            }

            fn value_kind(&self) -> crudkit_core::ValueKind {
                self.inner.value_kind()
            }

            fn is_optional(&self) -> bool {
                self.inner.is_optional()
            }
        }
    };
}

impl_dyn_field!(DynCreateField, ErasedCreateField, DynCreateModel);
impl_dyn_field!(DynReadField, ErasedReadField, DynReadModel);
impl_dyn_field!(DynUpdateField, ErasedUpdateField, DynUpdateModel);

/// A field of a create, read, or update model, convertible into the type-erased field of its
/// model's kind.
///
/// The `CkField` derive implements it for every field enum: a field of a create model converts
/// into a [`DynCreateField`], one of a read model into a [`DynReadField`], and one of an update
/// model into a [`DynUpdateField`]. This lets generic code, e.g. a form field component taking
/// `Club::Name`, find the state of the matching form by type.
pub trait IntoDynField: Clone + Send + Sync + 'static {
    /// The type-erased field type of this field's model kind.
    type Dyn: TypeErasedField;

    /// Converts this field into its type-erased form.
    fn into_dyn(self) -> Self::Dyn;
}

impl IntoDynField for DynCreateField {
    type Dyn = Self;

    fn into_dyn(self) -> Self {
        self
    }
}

impl IntoDynField for DynReadField {
    type Dyn = Self;

    fn into_dyn(self) -> Self {
        self
    }
}

impl IntoDynField for DynUpdateField {
    type Dyn = Self;

    fn into_dyn(self) -> Self {
        self
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use assertr::prelude::*;

    #[test]
    fn untagged_json_unwraps_the_type_tag() {
        let tagged = serde_json::json!({ "ReadItem": { "id": 1 } });

        assert_that!(untagged_json(&tagged)).is_equal_to(Ok(serde_json::json!({ "id": 1 })));
    }

    #[test]
    fn untagged_json_rejects_values_without_exactly_one_tag() {
        assert_that!(untagged_json(&serde_json::json!({ "a": 1, "b": 2 }))).is_equal_to(Err(
            UntaggedJsonError::UnexpectedShape("an object with several entries"),
        ));
        assert_that!(untagged_json(&serde_json::json!([1])))
            .is_equal_to(Err(UntaggedJsonError::UnexpectedShape("an array")));
    }
}
