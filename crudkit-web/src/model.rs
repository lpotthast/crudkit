#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DynReadOrUpdateModel {
    Read(DynReadModel),
    Update(DynUpdateModel),
}

impl From<DynReadModel> for DynReadOrUpdateModel {
    fn from(model: DynReadModel) -> Self {
        Self::Read(model)
    }
}

impl From<DynUpdateModel> for DynReadOrUpdateModel {
    fn from(model: DynUpdateModel) -> Self {
        Self::Update(model)
    }
}

/// This trait is implemented for each derived type (enum) describing a models fields.
///
/// Writing values is role-specific and therefore declared by `ErasedCreateField`, `ErasedReadField`,
/// and `ErasedUpdateField`.
#[typetag::serde]
pub trait ErasedField: Debug + Named + DynClone + DynEq + DynHash + Send + Sync {
    /// Returns the kind of value this field holds.
    fn value_kind(&self) -> crudkit_core::ValueKind;

    /// Returns whether this field is optional.
    fn is_optional(&self) -> bool;
}
dyn_eq::eq_trait_object!(ErasedField);
dyn_clone::clone_trait_object!(ErasedField);
dyn_hash::hash_trait_object!(ErasedField);

